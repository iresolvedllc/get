/**
 * Regenerates `.dev.vars` from the repository-root `.env`.
 *
 * Wrangler reads bindings from `.dev.vars`, not from an arbitrary env file.
 * The product-owned variables in `.env` use a `GET_` prefix, so this script
 * maps them to the binding names the Worker reads. The shared QStash
 * variables are already unprefixed and are copied as-is.
 *
 * Usage:
 *   bun run dev-vars     # write .dev.vars only
 *   bun run dev          # write .dev.vars, then start wrangler dev
 */

import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
const __ORIGINAL_URL = new URL(import.meta.url);

const here = dirname(fileURLToPath(__ORIGINAL_URL.href))
const serviceDir = join(here, '..')
const rootEnv = join(serviceDir, '.env')
const devVars = join(serviceDir, '.dev.vars')

const bindings = new Map<string, string>([
  ['GET_DATABASE_URL', 'DATABASE_URL'],
  ['GET_AWS_ACCESS_KEY_ID', 'AWS_ACCESS_KEY_ID'],
  ['GET_AWS_SECRET_ACCESS_KEY', 'AWS_SECRET_ACCESS_KEY'],
  ['GET_AWS_REGION', 'AWS_REGION'],
  ['GET_AWS_ENDPOINT_URL_S3', 'AWS_ENDPOINT_URL_S3'],
  ['GET_S3_BUCKET', 'S3_BUCKET'],
  ['GET_UPSTASH_REDIS_REST_URL', 'UPSTASH_REDIS_REST_URL'],
  ['GET_UPSTASH_REDIS_REST_TOKEN', 'UPSTASH_REDIS_REST_TOKEN'],
  ['QSTASH_CURRENT_SIGNING_KEY', 'QSTASH_CURRENT_SIGNING_KEY'],
  ['QSTASH_NEXT_SIGNING_KEY', 'QSTASH_NEXT_SIGNING_KEY'],
])

export async function writeDevVars(): Promise<void> {
  const source = await readFile(rootEnv, 'utf8')
  const output: string[] = [
    '# Generated by scripts/dev-vars.ts from .env. Do not commit.',
  ]

  for (const line of source.split('\n')) {
    const match = /^([A-Za-z_][A-Za-z0-9_]*)=(.*)$/.exec(line)
    if (!match) continue
    const [, name, value] = match
    const target = bindings.get(name!)
    if (!target) continue
    output.push(`${target}=${value}`)
  }

  await writeFile(devVars, `${output.join('\n')}\n`, { mode: 0o600 })
}

if (import.meta.main) {
  await writeDevVars()
}
