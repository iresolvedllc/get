import type { InstallContext } from '../products/types'

const ORIGIN_TOKEN = '__ORIGIN__'
const CHANNEL_TOKEN = '__CHANNEL__'
const VERSION_TOKEN = '__VERSION__'

export function renderKilnInstaller(context: InstallContext): string {
  return SHELL_SCRIPT.replaceAll(ORIGIN_TOKEN, context.origin)
    .replaceAll(CHANNEL_TOKEN, context.channel)
    .replaceAll(VERSION_TOKEN, context.version ?? '')
}

export function renderKilnPowerShellInstaller(context: InstallContext): string {
  return POWERSHELL_SCRIPT.replaceAll(ORIGIN_TOKEN, context.origin)
    .replaceAll(CHANNEL_TOKEN, context.channel)
    .replaceAll(VERSION_TOKEN, context.version ?? '')
}

const SHELL_SCRIPT = `#!/bin/sh
#
# Kiln installer, generated by the get release API.
#
# Usage:
#   curl -fsSL __ORIGIN__/kiln/install | sh
#   curl -fsSL "__ORIGIN__/kiln/install?channel=canary" | sh
#   curl -fsSL __ORIGIN__/kiln/install | sh -s 1.0.0
#
# Environment:
#   KILN_CHANNEL        release channel (default: __CHANNEL__)
#   KILN_INSTALL_ROOT   install root (default: $HOME/.kiln)

set -eu

TARGET_VERSION="\${1:-__VERSION__}"
CHANNEL="\${KILN_CHANNEL:-__CHANNEL__}"
API_BASE="__ORIGIN__"
INSTALL_ROOT="\${KILN_INSTALL_ROOT:-$HOME/.kiln}"
BIN_DIR="$INSTALL_ROOT/bin"

case "$CHANNEL" in
    stable|beta|rc|lts|alpha|canary) ;;
    *) echo "Invalid KILN_CHANNEL: '$CHANNEL' (expected stable, beta, rc, lts, alpha or canary)" >&2; exit 1 ;;
esac

os="$(uname -s)"
arch="$(uname -m)"
case "$os/$arch" in
    Linux/x86_64|Linux/amd64) PLATFORM="x86_64-unknown-linux-gnu" ;;
    Linux/aarch64|Linux/arm64) PLATFORM="aarch64-unknown-linux-gnu" ;;
    Darwin/x86_64) PLATFORM="x86_64-apple-darwin" ;;
    Darwin/arm64) PLATFORM="aarch64-apple-darwin" ;;
    *) echo "Unsupported platform: $os/$arch. Use install.ps1 on Windows." >&2; exit 1 ;;
esac

if [ "$os" = "Linux" ] && command -v ldd >/dev/null 2>&1; then
    if ldd --version 2>&1 | grep -qi musl; then
        echo "Unsupported libc: musl. Kiln currently ships glibc Linux builds." >&2
        exit 1
    fi
fi

if ! command -v unzip >/dev/null 2>&1; then
    echo "unzip is required to install Kiln" >&2
    exit 1
fi

if command -v curl >/dev/null 2>&1; then
    DOWNLOADER="curl"
elif command -v wget >/dev/null 2>&1; then
    DOWNLOADER="wget"
else
    echo "Either curl or wget is required but neither is installed" >&2
    exit 1
fi

download_file() {
    local_url="\${1:-}"
    local_output="\${2:-}"
    if [ "$DOWNLOADER" = "curl" ]; then
        if [ -n "$local_output" ]; then curl -fsSL -o "$local_output" "$local_url"; else curl -fsSL "$local_url"; fi
    else
        if [ -n "$local_output" ]; then wget -q -O "$local_output" "$local_url"; else wget -q -O - "$local_url"; fi
    fi
}

sha256_of() {
    if command -v sha256sum >/dev/null 2>&1; then
        sha256sum "\${1:-}" 2>/dev/null | awk '{print $1}' || true
    elif command -v shasum >/dev/null 2>&1; then
        shasum -a 256 "\${1:-}" 2>/dev/null | awk '{print $1}' || true
    else
        printf ''
    fi
}

manifest_url="\${API_BASE}/kiln/v1/update?channel=\${CHANNEL}&platform=\${PLATFORM}&format=text"
if [ -n "$TARGET_VERSION" ]; then
    manifest_url="\${manifest_url}&target=\${TARGET_VERSION}"
fi

manifest="$(download_file "$manifest_url")" || {
    echo "Error: failed to fetch release information from \${manifest_url}" >&2
    exit 1
}

LATEST=""
KIND=""
URL=""
SHA=""
SIZE=""

while IFS= read -r line; do
    case "$line" in
        artifact=*) KIND="\${line#artifact=}"; URL=""; SHA=""; SIZE="" ;;
        url=*)      URL="\${line#url=}" ;;
        sha256=*)   SHA="\${line#sha256=}" ;;
        size=*)     SIZE="\${line#size=}" ;;
        latest=*)   LATEST="\${line#latest=}" ;;
    esac
    if [ "$KIND" = "zip" ] && [ -n "$URL" ] && [ -n "$SHA" ] && [ -n "$SIZE" ]; then
        break
    fi
done <<EOF
$manifest
EOF

if [ -z "$LATEST" ] || [ -z "$URL" ] || [ -z "$SHA" ]; then
    echo "Error: the release API did not return a Kiln archive" >&2
    exit 1
fi

tmpdir="$(mktemp -d "\${TMPDIR:-/tmp}/kiln-install.XXXXXX")"
trap 'rm -rf "$tmpdir"' EXIT

archive="$tmpdir/kiln.zip"
download_file "$URL" "$archive"
actual="$(sha256_of "$archive")"
if [ -z "$actual" ] || [ "$actual" != "$SHA" ]; then
    echo "Error: checksum mismatch for Kiln \${LATEST}" >&2
    exit 1
fi

unzip -q "$archive" -d "$tmpdir/unpacked"
source_bin="$tmpdir/unpacked/kiln"
if [ ! -f "$source_bin" ]; then
    echo "Error: Kiln archive did not contain a kiln binary" >&2
    exit 1
fi

mkdir -p "$BIN_DIR"
chmod +x "$source_bin"
if ! "$source_bin" --version </dev/null >/dev/null 2>&1; then
    echo "Error: downloaded Kiln failed to run" >&2
    exit 1
fi
mv -f "$source_bin" "$BIN_DIR/kiln"
echo "Installed Kiln \${LATEST} to $BIN_DIR/kiln" >&2

case "$(basename "\${SHELL:-}")" in
    bash) config_file="$HOME/.bashrc" ;;
    zsh)  config_file="$HOME/.zshrc" ;;
    fish) config_file="$HOME/.config/fish/config.fish" ;;
    *)    config_file="" ;;
esac
if [ -n "$config_file" ]; then
    mkdir -p "$(dirname "$config_file")"
    if ! grep -qs "kiln installer" "$config_file" 2>/dev/null; then
        if [ "$(basename "\${SHELL:-}")" = "fish" ]; then
            printf '\\n# >>> kiln installer >>>\\nfish_add_path %s\\n# <<< kiln installer <<<\\n' "$BIN_DIR" >> "$config_file"
        else
            printf '\\n# >>> kiln installer >>>\\nexport PATH="%s:$PATH"\\n# <<< kiln installer <<<\\n' "$BIN_DIR" >> "$config_file"
        fi
    fi
fi

case ":$PATH:" in
    *":$BIN_DIR:"*) echo "Run 'kiln --version' to verify the install." >&2 ;;
    *) echo "Add $BIN_DIR to PATH to run kiln directly." >&2 ;;
esac
`

const POWERSHELL_SCRIPT = `# Kiln installer, generated by the get release API.
#
# Usage:
#   powershell -c "irm __ORIGIN__/kiln/install.ps1 | iex"
#
# Environment:
#   KILN_CHANNEL       release channel (default: __CHANNEL__)
#   KILN_INSTALL_ROOT  install root (default: $env:USERPROFILE\\.kiln)

$ErrorActionPreference = "Stop"

$Channel = if ($env:KILN_CHANNEL) { $env:KILN_CHANNEL } else { "__CHANNEL__" }
$InstallRoot = if ($env:KILN_INSTALL_ROOT) { $env:KILN_INSTALL_ROOT } else { Join-Path $env:USERPROFILE ".kiln" }
$BinDir = Join-Path $InstallRoot "bin"
$ApiBase = "__ORIGIN__"
$PinnedVersion = "__VERSION__"

if (@("stable", "beta", "rc", "lts", "alpha", "canary") -notcontains $Channel) {
    throw "Invalid KILN_CHANNEL: '$Channel' (expected stable, beta, rc, lts, alpha or canary)"
}

$Arch = $env:PROCESSOR_ARCHITECTURE
$Platform = if ($Arch -eq "ARM64") { "aarch64-pc-windows-msvc" } else { "x86_64-pc-windows-msvc" }

$ManifestUrl = "$ApiBase/kiln/v1/update?channel=$Channel&platform=$Platform"
if ($PinnedVersion) {
    $ManifestUrl = "$ManifestUrl&target=$PinnedVersion"
}
$Manifest = Invoke-RestMethod -Uri $ManifestUrl -UseBasicParsing
if (-not $Manifest.latest -or -not $Manifest.url -or -not $Manifest.sha256) {
    throw "The release API did not return a Kiln archive"
}

$Tmp = Join-Path ([System.IO.Path]::GetTempPath()) ("kiln-install-" + [Guid]::NewGuid().ToString("N"))
New-Item -ItemType Directory -Path $Tmp | Out-Null
try {
    $Archive = Join-Path $Tmp "kiln.zip"
    Invoke-WebRequest -Uri $Manifest.url -OutFile $Archive -UseBasicParsing
    $Actual = (Get-FileHash -Algorithm SHA256 -Path $Archive).Hash.ToLowerInvariant()
    if ($Actual -ne $Manifest.sha256.ToLowerInvariant()) {
        throw "Checksum mismatch for Kiln $($Manifest.latest)"
    }

    $Unpacked = Join-Path $Tmp "unpacked"
    Expand-Archive -Path $Archive -DestinationPath $Unpacked -Force
    $Source = Join-Path $Unpacked "kiln.exe"
    if (-not (Test-Path $Source)) {
        throw "Kiln archive did not contain kiln.exe"
    }

    New-Item -ItemType Directory -Path $BinDir -Force | Out-Null
    $Target = Join-Path $BinDir "kiln.exe"
    Copy-Item -Path $Source -Destination $Target -Force

    & $Target --version | Out-Null
    if ($LASTEXITCODE -ne 0) {
        throw "Downloaded Kiln failed to run"
    }

    $UserPath = [Environment]::GetEnvironmentVariable("Path", "User")
    if (($UserPath -split ";") -notcontains $BinDir) {
        [Environment]::SetEnvironmentVariable("Path", "$UserPath;$BinDir", "User")
    }
    if (($env:Path -split ";") -notcontains $BinDir) {
        $env:Path = "$env:Path;$BinDir"
    }

    Write-Host "Installed Kiln $($Manifest.latest) to $Target"
} finally {
    Remove-Item -Recurse -Force $Tmp -ErrorAction SilentlyContinue
}
`
