/**
 * The install script, rendered per request.
 *
 * The script is generated so it always reflects the current channel set and
 * the current API origin. It resolves a download URL at *install* time by
 * calling the API, so the URL it uses is always fresh — a presigned URL
 * embedded at render time would expire before the script was ever run.
 *
 * The script deliberately depends on nothing but a POSIX shell, `curl` or
 * `wget`, and the standard `sha256sum`/`shasum`. No `jq`, no `python3`: the
 * API offers a `format=text` rendering for exactly this reason.
 */

export interface BuildInstallOptions {
	/** Origin the API is reachable at, e.g. https://get.example.com. */
	origin: string
	/** Channel the script installs from when the caller does not pick one. */
	channel: string
	/** Optional version pinned by the install endpoint. */
	version?: string | null
}

/** Placeholders substituted into the script body. */
const ORIGIN_TOKEN = '__ORIGIN__'
const CHANNEL_TOKEN = '__CHANNEL__'
const VERSION_TOKEN = '__VERSION__'

export function renderBuildInstaller(options: BuildInstallOptions): string {
	return SCRIPT.replaceAll(ORIGIN_TOKEN, options.origin)
		.replaceAll(CHANNEL_TOKEN, options.channel)
		.replaceAll(VERSION_TOKEN, options.version ?? '')
}

const SCRIPT = `#!/usr/bin/env bash
#
# Build CLI installer — generated by the \`get\` release API.
#
# Usage:
#   curl -fsSL __ORIGIN__/build/install | bash
#   curl -fsSL "__ORIGIN__/build/install?channel=nightly" | bash
#   curl -fsSL __ORIGIN__/build/install | bash -s 0.2.0
#
# Environment:
#   BUILD_CHANNEL   release channel to install (default: __CHANNEL__)
#   BUILD_BIN_DIR   directory for the \`build\` symlink (default: $HOME/.build/bin)
#
# No account, deployment key, or hosted configuration is required.

set -euo pipefail

TARGET_VERSION="\${1:-__VERSION__}"
CHANNEL="\${BUILD_CHANNEL:-__CHANNEL__}"
PLATFORM="linux-x86_64"
API_BASE="__ORIGIN__"

case "$CHANNEL" in
    stable|beta|nightly) ;;
    *) echo "Invalid BUILD_CHANNEL: '$CHANNEL' (expected stable, beta or nightly)" >&2; exit 1 ;;
esac

if [ -n "$TARGET_VERSION" ] && ! [[ "$TARGET_VERSION" =~ ^[0-9]+\\.[0-9]+\\.[0-9]+(-[0-9A-Za-z.-]+)?$ ]]; then
    echo "Invalid version format: $TARGET_VERSION (expected X.Y.Z or X.Y.Z-suffix)" >&2
    exit 1
fi

case "$(uname -s)" in
    Linux) ;;
    *) echo "Unsupported OS: $(uname -s) (this build is linux x64 only)" >&2; exit 1 ;;
esac
case "$(uname -m)" in
    x86_64|amd64|AMD64) ;;
    *) echo "Unsupported architecture: $(uname -m) (x86_64 only)" >&2; exit 1 ;;
esac

DOWNLOADER=""
if command -v curl >/dev/null 2>&1; then
    DOWNLOADER="curl"
elif command -v wget >/dev/null 2>&1; then
    DOWNLOADER="wget"
else
    echo "Either curl or wget is required but neither is installed" >&2
    exit 1
fi

download_file() {
    local url="\${1:-}" output="\${2:-}"
    if [ "$DOWNLOADER" = "curl" ]; then
        if [ -n "$output" ]; then
            curl -fsSL -o "$output" "$url"
        else
            curl -fsSL "$url"
        fi
    else
        if [ -n "$output" ]; then
            wget -q -O "$output" "$url"
        else
            wget -q -O - "$url"
        fi
    fi
}

# Parallel byte-range download.
#
# The size comes from the API, so no HEAD probe is needed — and none would
# work here, because a presigned URL is signed for GET only. Falls back to a
# single connection for small files or when curl is unavailable.
download_file_parallel() {
    local url="\${1:-}" output="\${2:-}" size="\${3:-}"
    if [ "$DOWNLOADER" != "curl" ]; then
        download_file "$url" "$output"
        return
    fi
    if [ -z "$size" ] || ! [ "$size" -ge 16777216 ] 2>/dev/null; then
        download_file "$url" "$output"
        return
    fi
    local n=8
    local chunk_size=$(( (size + n - 1) / n ))
    local tmpdir
    tmpdir=$(mktemp -d 2>/dev/null) || { download_file "$url" "$output"; return; }
    local pids=() i start end
    for i in $(seq 0 $((n - 1))); do
        start=$((i * chunk_size))
        end=$((start + chunk_size - 1))
        [ $end -ge $size ] && end=$((size - 1))
        curl -fsSL -r "\${start}-\${end}" -o "\${tmpdir}/$(printf 'chunk.%03d' "$i")" "$url" &
        pids+=($!)
    done
    local all_ok=true pid
    for pid in "\${pids[@]}"; do
        wait "$pid" || all_ok=false
    done
    if [ "$all_ok" = true ] && cat "\${tmpdir}"/chunk.* > "$output" 2>/dev/null; then
        rm -rf "$tmpdir"
        return 0
    fi
    rm -rf "$tmpdir"
    download_file "$url" "$output"
}

# Checksum of a file, or the empty string when no sha256 tool is available.
sha256_of() {
    if command -v sha256sum >/dev/null 2>&1; then
        sha256sum "\${1:-}" 2>/dev/null | awk '{print $1}' || true
    elif command -v shasum >/dev/null 2>&1; then
        shasum -a 256 "\${1:-}" 2>/dev/null | awk '{print $1}' || true
    else
        printf ''
    fi
}

manifest_url="\${API_BASE}/build/v1/update?channel=\${CHANNEL}&platform=\${PLATFORM}&format=text"
if [ -n "$TARGET_VERSION" ]; then
    manifest_url="\${manifest_url}&target=\${TARGET_VERSION}"
fi

if [ -z "$TARGET_VERSION" ]; then
    echo "Fetching the latest \${CHANNEL} release..." >&2
else
    echo "Fetching the \${CHANNEL} release \${TARGET_VERSION}..." >&2
fi

manifest="$(download_file "$manifest_url")" || {
    echo "Error: failed to fetch release information from \${manifest_url}" >&2
    exit 1
}

LATEST=""
KIND=""
URL=""
SHA=""
SIZE=""
RAW_URL=""; RAW_SHA=""; RAW_SIZE=""
GZIP_URL=""; GZIP_SHA=""; GZIP_SIZE=""
ZSTD_URL=""; ZSTD_SHA=""; ZSTD_SIZE=""

save_artifact() {
    case "$KIND" in
        raw)  RAW_URL="$URL";  RAW_SHA="$SHA";  RAW_SIZE="$SIZE" ;;
        gzip) GZIP_URL="$URL"; GZIP_SHA="$SHA"; GZIP_SIZE="$SIZE" ;;
        zstd) ZSTD_URL="$URL"; ZSTD_SHA="$SHA"; ZSTD_SIZE="$SIZE" ;;
    esac
}

# The manifest is read with a here-string so its contents are never
# re-evaluated by the shell.
while IFS= read -r line; do
    case "$line" in
        artifact=*)
            if [ -n "$KIND" ]; then save_artifact; fi
            KIND="\${line#artifact=}"
            URL=""; SHA=""; SIZE=""
            ;;
        url=*)    URL="\${line#url=}" ;;
        sha256=*) SHA="\${line#sha256=}" ;;
        size=*)   SIZE="\${line#size=}" ;;
        latest=*) LATEST="\${line#latest=}" ;;
    esac
done <<< "$manifest"

if [ -n "$KIND" ]; then save_artifact; fi

if [ -z "$LATEST" ]; then
    echo "Error: the API did not report a version for the \${CHANNEL} channel" >&2
    exit 1
fi

DOWNLOAD_DIR="$HOME/.build/downloads"
BIN_DIR="\${BUILD_BIN_DIR:-$HOME/.build/bin}"
mkdir -p "$DOWNLOAD_DIR" "$BIN_DIR"

binary_path="\${DOWNLOAD_DIR}/build-\${LATEST}-\${PLATFORM}"
INSTALLED_FILE=""

cleanup() {
    if [ -n "$INSTALLED_FILE" ]; then
        rm -f "$INSTALLED_FILE"
    fi
}
trap cleanup EXIT

# Fetch one artifact, verify it, and decompress it when it is compressed.
# Leaves the usable file in INSTALLED_FILE and returns 0 on success.
attempt_artifact() {
    local kind="\${1:-}" url="\${2:-}" sha="\${3:-}" size="\${4:-}"
    if [ -z "$url" ]; then
        return 1
    fi
    if [ "$kind" = "zstd" ] && ! command -v zstd >/dev/null 2>&1; then
        return 1
    fi
    if [ "$kind" = "gzip" ] && ! command -v gzip >/dev/null 2>&1; then
        return 1
    fi

    local tmp
    tmp="$(mktemp "\${DOWNLOAD_DIR}/.download.XXXXXX")" || return 1

    if ! download_file_parallel "$url" "$tmp" "$size"; then
        rm -f "$tmp"
        return 1
    fi

    if [ -z "$sha" ]; then
        echo "Error: the \${kind} artifact has no checksum; refusing to install" >&2
        rm -f "$tmp"
        return 1
    fi
    local actual
    actual="$(sha256_of "$tmp")"
    if [ -z "$actual" ]; then
        echo "Error: sha256sum or shasum is required to verify the download" >&2
        rm -f "$tmp"
        return 1
    fi
    if [ "$actual" != "$sha" ]; then
        echo "Error: checksum mismatch on the \${kind} artifact (expected \${sha}, got \${actual})" >&2
        rm -f "$tmp"
        return 1
    fi

    if [ "$kind" != "raw" ]; then
        local out
        out="$(mktemp "\${DOWNLOAD_DIR}/.download.XXXXXX")" || { rm -f "$tmp"; return 1; }
        if [ "$kind" = "zstd" ]; then
            zstd -q -dc "$tmp" > "$out" 2>/dev/null || { rm -f "$tmp" "$out"; return 1; }
        else
            gzip -dc "$tmp" > "$out" 2>/dev/null || { rm -f "$tmp" "$out"; return 1; }
        fi
        rm -f "$tmp"
        tmp="$out"
        # The decompressed binary has to match the raw artifact's checksum.
        # A missing checksum is a refusal, not a skip: the compressed blob's
        # own hash does not prove the bytes that will be executed.
        if [ -z "$RAW_SHA" ]; then
            echo "Error: the release has no checksum for the raw binary" >&2
            rm -f "$tmp"
            return 1
        fi
        local actual
        actual="$(sha256_of "$tmp")"
        if [ -z "$actual" ] || [ "$actual" != "$RAW_SHA" ]; then
            echo "Error: the decompressed binary does not match the expected checksum" >&2
            rm -f "$tmp"
            return 1
        fi
    fi

    INSTALLED_FILE="$tmp"
    return 0
}

echo "Installing Build \${LATEST} (\${PLATFORM}) from the \${CHANNEL} channel..." >&2

if attempt_artifact zstd "$ZSTD_URL" "$ZSTD_SHA" "$ZSTD_SIZE"; then
    :
elif attempt_artifact gzip "$GZIP_URL" "$GZIP_SHA" "$GZIP_SIZE"; then
    :
elif attempt_artifact raw "$RAW_URL" "$RAW_SHA" "$RAW_SIZE"; then
    :
else
    echo "Error: could not download Build \${LATEST} for \${PLATFORM}" >&2
    exit 1
fi

chmod +x "$INSTALLED_FILE"

# Smoke-test before activating so a bad build never replaces a working install.
if ! "$INSTALLED_FILE" --version </dev/null >/dev/null 2>&1; then
    echo "Error: downloaded build failed to run; keeping the existing install." >&2
    exit 1
fi

mv -f "$INSTALLED_FILE" "$binary_path"
INSTALLED_FILE=""

# Relative symlinks when the bin and download directories share a parent, so
# they survive a remapped $HOME in a container.
if [ "$(dirname "$BIN_DIR")" = "$(dirname "$DOWNLOAD_DIR")" ]; then
    link_target="../$(basename "$DOWNLOAD_DIR")/$(basename "$binary_path")"
else
    link_target="$binary_path"
fi
ln -sf "$link_target" "$BIN_DIR/build"
ln -sf "$link_target" "$BIN_DIR/agent"
echo "  Binary installed to $binary_path and linked to $BIN_DIR/build." >&2

# Generate shell completions (best-effort).
mkdir -p "$HOME/.build/completions/bash" "$HOME/.build/completions/zsh"
"$BIN_DIR/build" completions bash > "$HOME/.build/completions/bash/build.bash" 2>/dev/null || true
"$BIN_DIR/build" completions zsh  > "$HOME/.build/completions/zsh/_build"     2>/dev/null || true
if mkdir -p "$HOME/.config/fish/completions" 2>/dev/null; then
    "$BIN_DIR/build" completions fish > "$HOME/.config/fish/completions/build.fish" 2>/dev/null || true
fi

# Record the installer and the channel so \`build update\` knows where to look.
CONFIG_FILE="$HOME/.build/config.toml"
CLI_BLOCK="$(printf 'installer = "internal"\\nchannel = "%s"' "$CHANNEL")"
if [ ! -f "$CONFIG_FILE" ]; then
    printf '[cli]\\n%s\\n' "$CLI_BLOCK" > "$CONFIG_FILE"
elif grep -q '^\\[cli\\]' "$CONFIG_FILE"; then
    tmp="$CONFIG_FILE.tmp.$$"
    awk -v block="$CLI_BLOCK" '
        /^\\[cli\\][[:space:]]*(#.*)?$/ { print; printf "%s\\n", block; in_cli=1; next }
        /^\\[.*\\][[:space:]]*(#.*)?$/  { in_cli=0 }
        in_cli && /^[[:space:]]*(installer|channel)[[:space:]]*=/ { next }
        { print }
    ' "$CONFIG_FILE" > "$tmp" && mv "$tmp" "$CONFIG_FILE"
else
    printf '\\n[cli]\\n%s\\n' "$CLI_BLOCK" >> "$CONFIG_FILE"
fi

path_has_dir() {
    case ":$PATH:" in *":$1:"*) return 0 ;; *) return 1 ;; esac
}

# Symlink into a directory already on PATH so build works without a restart.
SYMLINK_CREATED=""
if ! path_has_dir "$BIN_DIR"; then
    for candidate in "$HOME/.local/bin" "/usr/local/bin"; do
        if path_has_dir "$candidate" && [ -d "$candidate" ] && [ -w "$candidate" ]; then
            ln -sf "$BIN_DIR/build" "$candidate/build"
            ln -sf "$BIN_DIR/agent" "$candidate/agent"
            SYMLINK_CREATED="$candidate"
            echo "  Symlinked $candidate/build -> $BIN_DIR/build" >&2
            break
        fi
    done
fi

# Persist the PATH entry for future shells.
user_shell="$(basename "\${SHELL:-}")"
config_file=""
case "$user_shell" in
    bash) config_file="$HOME/.bashrc" ;;
    zsh)  config_file="$HOME/.zshrc" ;;
    fish) config_file="$HOME/.config/fish/config.fish" ;;
esac

if [ -n "$config_file" ]; then
    mkdir -p "$(dirname "$config_file")"

    if [ "$user_shell" = "fish" ]; then
        new_block='# >>> build installer >>>
fish_add_path $HOME/.build/bin
# <<< build installer <<<'
    elif [ "$user_shell" = "zsh" ]; then
        new_block='# >>> build installer >>>
export PATH="$HOME/.build/bin:$PATH"
fpath=(~/.build/completions/zsh $fpath)
autoload -Uz compinit && compinit -C
# <<< build installer <<<'
    else
        new_block='# >>> build installer >>>
export PATH="$HOME/.build/bin:$PATH"
[[ -r ~/.build/completions/bash/build.bash ]] && source ~/.build/completions/bash/build.bash
# <<< build installer <<<'
    fi

    if grep -qs "build installer" "$config_file" 2>/dev/null; then
        tmp="$config_file.tmp.$$"
        awk '
            /# >>> build installer >>>/ { skip=1; next }
            /# <<< build installer <<<$/ { skip=0; next }
            !skip { print }
        ' "$config_file" > "$tmp" && mv "$tmp" "$config_file"
    else
        [ -f "$config_file" ] && cp "$config_file" "$config_file.bak.$(date +%s)"
    fi

    printf '\\n%s\\n' "$new_block" >> "$config_file"
    echo "  Updated $BIN_DIR in PATH in $config_file." >&2
fi

echo "" >&2
if path_has_dir "$BIN_DIR" || [ -n "$SYMLINK_CREATED" ]; then
    echo "Run 'build' or 'agent' to get started!" >&2
elif [ -n "$config_file" ]; then
    echo "Restart your terminal, then run 'build' or 'agent' to get started!" >&2
else
    echo "Add $BIN_DIR to your PATH, then run 'build' or 'agent':" >&2
    echo '  export PATH="$HOME/.build/bin:$PATH"' >&2
fi
`
